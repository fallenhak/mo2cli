# Header MO2 writes at the top of modlist.txt / plugins.txt / loadorder.txt
# (profile.cpp doWriteModlist, pluginlist.cpp).
_PROFILE_HEADER = "# This file was automatically generated by Mod Organizer.\r\n"

# MO2's game plugin directory name for "My Games" per edition
# (modorganizer-game_skyrimse: gameDirectoryName()).
_MY_GAMES_DIRECTORIES = {
    "Steam": "Skyrim Special Edition",
    "GOG": "Skyrim Special Edition GOG",
    "Epic Games": "Skyrim Special Edition EPIC",
}


def initialize(path: str | Path, game_name: str, game_path: str | Path, profile: str = "Default", force: bool = False) -> dict[str, object]:
    root = Path(path).expanduser().resolve()
    _safe_name(profile)
    if root.exists() and any(root.iterdir()) and not force:
        raise Mo2Error(f"Instance directory is not empty; use --force to proceed: {root}")
    root.mkdir(parents=True, exist_ok=True)
    for directory in ("mods", "profiles", "downloads", "overwrite"):
        (root / directory).mkdir(parents=True, exist_ok=True)
    profile_dir = root / "profiles" / profile
    profile_dir.mkdir(parents=True, exist_ok=True)
    write_text(profile_dir / "modlist.txt", "# This file was automatically generated by Mod Organizer.\r\n")
    for filename in ("archives.txt", "plugins.txt", "loadorder.txt"):
        if not (profile_dir / filename).exists():
            write_text(profile_dir / filename, "")
    game = Path(game_path).expanduser().resolve()
    ini = "\r\n".join([
        "[General]",
        f"gameName={game_name}",
        f"gamePath={game}",
        f"selected_profile={profile}",
        "",
        "[Settings]",
        "base_directory=%BASE_DIR%",
        "mod_directory=%BASE_DIR%/mods",
        "profiles_directory=%BASE_DIR%/profiles",
        "download_directory=%BASE_DIR%/downloads",
        "overwrite_directory=%BASE_DIR%/overwrite",
        "",
    ])
    write_text(root / "ModOrganizer.ini", ini)
    return {"instance": str(root), "game": game_name, "game_path": str(game), "profile": profile}


def detect_game_edition(game_path: Path) -> str:
    """Same file probes as the MO2 Skyrim SE game plugin's ``checkVariants()``."""
    if (game_path / "Galaxy64.dll").exists():
        return "GOG"
    if (game_path / "EOSSDK-Win64-Shipping.dll").exists():
        return "Epic Games"
    return "Steam"


def _my_games_candidates(directory_name: str, override: Path | None) -> list[Path]:
    if override is not None:
        return [override]
    roots: list[Path] = []
    for variable in ("OneDrive", "OneDriveConsumer", "OneDriveCommercial"):
        if os.environ.get(variable):
            roots.append(Path(os.environ[variable]) / "Documents")
    roots.append(Path.home() / "Documents")
    return [root / "My Games" / directory_name for root in roots]


def _find_file(directory: Path, name: str) -> Path | None:
    if not directory.is_dir():
        return None
    wanted = name.casefold()
    return next((item for item in directory.iterdir() if item.is_file() and item.name.casefold() == wanted), None)


def render_mo2_ini(game_name: str, game_path: Path, edition: str | None, profile: str, version: str | None) -> str:
    """Render ``ModOrganizer.ini`` the way MO2 2.5.2 writes a new portable instance.

    ``CreateInstanceDialog::finish()`` (createinstancedialog.cpp) writes
    ``gameName``, ``gamePath`` (a QByteArray, hence ``@ByteArray`` with doubled
    backslashes), ``game_edition`` and the three profile defaults; for a
    portable instance ``base_directory`` and the four path settings are only
    written when they differ from the ``%BASE_DIR%/<dir>`` defaults, so they are
    absent. ``selected_profile`` (also a QByteArray) is written by MO2 as soon as
    a profile is loaded, ``version`` by ``Settings::processUpdates`` and
    ``first_start`` once the first-start tutorial has run.
    """
    general = [
        "[General]",
        f"gameName={qsettings.encode(game_name)}",
        f"gamePath={qsettings.encode_byte_array(str(game_path).replace('/', chr(92)))}",
    ]
    if edition:
        general.append(f"game_edition={qsettings.encode(edition)}")
    general.append(f"selected_profile={qsettings.encode_byte_array(profile)}")
    if version:
        general.append(f"version={version}")
    general.append("first_start=false")
    settings = [
        "[Settings]",
        "profile_local_inis=true",
        "profile_local_saves=true",
        "profile_archive_invalidation=false",
    ]
    return "\r\n".join(general + [""] + settings + [""])


def initialize_portable(
    path: str | Path,
    mo2_archive: str | Path,
    game_name: str,
    game_path: str | Path,
    profile: str = "Default",
    force: bool = False,
    dry_run: bool = False,
    mo2_url: str | None = None,
    my_games: str | Path | None = None,
) -> dict[str, object]:
    """Build a portable MO2 instance from the official MO2 archive.

    Layout: the extracted MO2 files, ``portable.txt``, ``downloads`` (holding the
    MO2 archive itself with a ``.meta``), ``mods``, ``overwrite``,
    ``profiles\\<profile>`` with the files MO2 expects, and a
    ``ModOrganizer.ini`` using ``game_path`` (typically ``<dir>\\Stock Game``).
    """
    root = Path(path).expanduser().resolve()
    archive = Path(mo2_archive).expanduser().resolve()
    _safe_name(profile)
    if not archive.is_file():
        raise Mo2Error(f"MO2 archive not found: {archive}")
    game = Path(game_path).expanduser().resolve()
    # The game folder (typically "<dir>\Stock Game") may already sit inside the
    # target directory; anything else makes the directory non-empty.
    game_top = game.relative_to(root).parts[0] if game != root and game.is_relative_to(root) else None
    leftovers = [item.name for item in root.iterdir() if item.name.casefold() != (game_top or "").casefold()] if root.is_dir() else []
    if leftovers and not force:
        raise Mo2Error(f"Instance directory is not empty ({', '.join(sorted(leftovers)[:5])}); use --force to proceed: {root}")
    records = list_archive(archive)
    has_top_level_exe = any(
        str(item["name"]).replace("\\", "/").casefold() == "modorganizer.exe" for item in records if not item.get("directory")
    )
    wrapper = None if has_top_level_exe else archive_common_root(records)
    if not has_top_level_exe and wrapper is None:
        raise Mo2Error("The archive does not look like Mod Organizer 2: no ModOrganizer.exe at its top level or inside a single root folder.")
    version_match = re.search(r"(\d+\.\d+\.\d+(?:\.\d+)?)", archive.name)
    version = version_match.group(1) if version_match else None
    is_skyrim_se = game_name.casefold() == "skyrim special edition"
    edition = detect_game_edition(game) if is_skyrim_se else None
    archive_in_downloads = (root / "downloads" / archive.name)
    result: dict[str, object] = {
        "instance": str(root),
        "portable": True,
        "game": game_name,
        "game_path": str(game),
        "game_path_exists": game.is_dir(),
        "game_edition": edition,
        "profile": profile,
        "mo2_archive": str(archive),
        "mo2_version": version,
        "strip_root": wrapper,
        "downloads_archive": str(archive_in_downloads),
    }
    if not game.is_dir():
        result["warning"] = "Game path does not exist yet; create it (for example copy the game into 'Stock Game') before launching MO2."
    if dry_run:
        result["dry_run"] = True
        result["would_create"] = ["portable.txt", "ModOrganizer.ini", "downloads", "mods", "overwrite", f"profiles/{profile}"]
        return result

    extraction = extract_to_directory(archive, root, strip_root=wrapper is not None, replace=True, require="ModOrganizer.exe")
    result["files_extracted"] = extraction["files"]
    write_text(root / "portable.txt", "")
    for directory in ("downloads", "mods", "overwrite", "profiles"):
        (root / directory).mkdir(parents=True, exist_ok=True)
    profile_dir = root / "profiles" / profile
    profile_dir.mkdir(parents=True, exist_ok=True)
    write_text(profile_dir / "modlist.txt", _PROFILE_HEADER)
    write_text(profile_dir / "archives.txt", "")
    write_text(profile_dir / "plugins.txt", _PROFILE_HEADER)
    write_text(profile_dir / "loadorder.txt", _PROFILE_HEADER)
    # Profile settings.ini: QSettings writes keys with no group under [General]
    # (profile.cpp findProfileSettings/storeSetting).
    write_text(
        profile_dir / "settings.ini",
        "\r\n".join(["[General]", "LocalSaves=true", "LocalSettings=true", "AutomaticArchiveInvalidation=false", ""]),
    )
    result["profile_inis"] = _seed_profile_inis(profile_dir, game, edition, Path(my_games) if my_games else None) if is_skyrim_se else []
    if version is None:
        # Not in the archive name: read it from the executable's file version.
        exe_version = _windows_file_version(root / "ModOrganizer.exe")
        if exe_version:
            version = exe_version[:-2] if exe_version.endswith(".0") else exe_version
        result["mo2_version"] = version
    write_text(root / "ModOrganizer.ini", render_mo2_ini(game_name, game, edition, profile, version))

    downloads = root / "downloads"
    if archive.parent != downloads.resolve():
        shutil.copy2(archive, archive_in_downloads)
    write_meta(
        archive_in_downloads.with_name(archive.name + ".meta"),
        direct_url=mo2_url,
        name=archive.name,
        mod_name="Mod Organizer 2",
        version=version,
        installed=True,
        defaults={"removed": False},
    )
    result["meta"] = str(archive_in_downloads.with_name(archive.name + ".meta"))
    if mo2_url is None:
        result["note"] = "No --mo2-url: add a Wabbajack source with 'mo2 downloads meta <archive> --direct-url <GitHub release asset URL>'."
    return result


def _seed_profile_inis(profile_dir: Path, game: Path, edition: str | None, my_games: Path | None) -> list[str]:
    """Copy the profile-local game INIs the way the SkyrimSE game plugin does.

    ``GameSkyrimSE::initializeProfile`` copies ``skyrim_default.ini`` from the
    game folder as ``skyrim.ini`` when asked for defaults (or when the user's
    ``skyrim.ini`` is missing) and ``skyrimprefs.ini`` / ``skyrimcustom.ini``
    from ``Documents\\My Games\\<game>``. Missing sources are skipped; MO2 recreates
    them from the game on first launch.
    """
    directory_name = _MY_GAMES_DIRECTORIES.get(edition or "Steam", "Skyrim Special Edition")
    documents = next((c for c in _my_games_candidates(directory_name, my_games) if c.is_dir()), None)
    copied: list[str] = []

    def copy(source: Path | None, target_name: str) -> None:
        if source is not None and source.is_file():
            shutil.copyfile(source, profile_dir / target_name)
            copied.append(target_name)

    copy(_find_file(game, "skyrim_default.ini") or (_find_file(documents, "skyrim.ini") if documents else None), "skyrim.ini")
    if documents is not None:
        copy(_find_file(documents, "skyrimprefs.ini"), "skyrimprefs.ini")
        copy(_find_file(documents, "skyrimcustom.ini"), "skyrimcustom.ini")
    return copied
